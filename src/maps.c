void world_map_data(MapId map, const WorldShape **solids, int *count, const WorldCover **covers, int *cover_count) {
    if (map == MAP_VILLAGE) {
        *solids=village_solids; *count=sizeof village_solids/sizeof *village_solids;
        *covers=village_covers; *cover_count=sizeof village_covers/sizeof *village_covers;
    }
    else if (map == MAP_PASS) {
        *solids=pass_solids; *count=sizeof pass_solids/sizeof *pass_solids;
        *covers=pass_covers; *cover_count=sizeof pass_covers/sizeof *pass_covers;
    }
    else if (map == MAP_CAVE) {
        *solids=cave_solids; *count=sizeof cave_solids/sizeof *cave_solids;
        *covers=0; *cover_count=0;
    }
}

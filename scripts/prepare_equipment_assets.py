#!/usr/bin/env python3
"""Non-destructively crop/alpha-resize the south-view cutout prototype."""
import hashlib
import json
from pathlib import Path
from PIL import Image
from prepare_technique_assets import pose_mask

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/hero/equipment'
NAMES = ['head', 'tunic', 'sash', 'right_upper_arm', 'right_forearm_hand',
         'left_upper_arm', 'left_forearm_hand', 'right_base_leg', 'left_base_leg',
         'armor_torso', 'right_armor_leg', 'left_armor_leg', 'helmet',
         'plain_hwando', 'ornate_hwando', 'pelvis']


def main():
    source = ART / 'cutout-south-master.png'
    image = Image.open(source).convert('RGBA')
    assert image.getextrema()[3][0] == 0, 'Source is not transparent'
    atlas = Image.new('RGBA', (1024, 1024))
    records = []
    for i, name in enumerate(NAMES):
        selected_source = ART / 'helmet-open-master.png' if i == 12 else source
        selected_image = Image.open(selected_source).convert('RGBA') if i == 12 else image
        assert selected_image.size == image.size
        x, y = i % 4, i // 4
        box = (round(x * image.width / 4), round(y * image.height / 4),
               round((x + 1) * image.width / 4), round((y + 1) * image.height / 4))
        # A few swords/boots cross a nominal row. Select the connected part
        # on the full master, rather than cutting at that row boundary.
        cell_alpha = selected_image.getchannel('A').crop(box)
        cx, cy = cell_alpha.width / 2, cell_alpha.height / 2
        candidates = [(px, py) for py in range(cell_alpha.height)
                      for px in range(cell_alpha.width) if cell_alpha.getpixel((px, py)) > 32]
        sx, sy = min(candidates, key=lambda p: (p[0]-cx)**2 + (p[1]-cy)**2)
        mask = pose_mask(selected_image.getchannel('A'), (box[0]+sx, box[1]+sy))
        part = selected_image.copy()
        part.putalpha(mask)
        # Remove only almost-transparent specks; never select by red/RGB color.
        alpha = part.getchannel('A').point(lambda a: 0 if a < 5 else a)
        part.putalpha(alpha)
        bounds = alpha.getbbox()
        assert bounds, name
        assert bounds[0] > 0 and bounds[1] > 0, (name, 'source touches edge')
        assert bounds[2] < image.width and bounds[3] < image.height, name
        assert bounds[2]-bounds[0] < 320 and bounds[3]-bounds[1] < 340, (name, bounds)
        part = part.crop(bounds)
        if i == 12:
            assert part.getpixel((part.width//2, round(part.height*.72)))[3] == 0, 'Helmet must expose face'
        # Each runtime tile contains a 224px-high part with original proportions.
        scale = min(224 / part.width, 224 / part.height)
        size = (round(part.width * scale), round(part.height * scale))
        part = part.convert('RGBa').resize(size, Image.Resampling.LANCZOS).convert('RGBA')
        ox, oy = (256 - size[0]) // 2, (256 - size[1]) // 2
        atlas.paste(part, (x * 256 + ox, y * 256 + oy))
        records.append(dict(name=name, source=selected_source.name,
                            source_sha256=hashlib.sha256(selected_source.read_bytes()).hexdigest(),
                            source_cell=list(box), source_bounds=list(bounds),
                            rect=[x*256+ox, y*256+oy, *size]))
    output = ART / 'cutout-south-v1.png'
    atlas.save(output)
    metadata = dict(source_size=list(image.size), source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                    output_sha256=hashlib.sha256(output.read_bytes()).hexdigest(),
                    transparent_fraction=atlas.getchannel('A').histogram()[0] / (1024*1024),
                    parts=records, processing='alpha<5 specks only; crop; premultiplied Lanczos; no flip/recolor/paint')
    (ART / 'preparation.json').write_text(json.dumps(metadata, indent=2)+'\n', encoding='utf-8')
    header = ['/* Generated by scripts/prepare_equipment_assets.py. */',
              'static const SDL_Rect EQUIPMENT_RECTS[EQUIPMENT_PART_COUNT] = {']
    header += ['    {%s}, /* %s */' % (', '.join(map(str, p['rect'])), p['name']) for p in records]
    header += ['};', '']
    (ROOT/'src/equipment_atlas_data.h').write_text('\n'.join(header), encoding='utf-8')
    print(json.dumps({k:v for k,v in metadata.items() if k != 'parts'}))


if __name__ == '__main__':
    main()

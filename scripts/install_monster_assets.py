#!/usr/bin/env python3
"""Install approved monster art and generate the renderer's scale contract.

Run prepare_monster_assets.py first. The butcher's short-attack candidate stays
in art/: the current AI has one heavy strike, represented by the skill sheet.
"""
from pathlib import Path
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/monsters'
NAMES = ('boar-idle','boar-walk','boar-attack',
         'butcher-idle','butcher-walk','butcher-skill')


def main():
    report = json.loads((ART/'preparation.json').read_text(encoding='utf-8'))
    out = ROOT/'assets/monsters'
    out.mkdir(exist_ok=True)
    rows = []
    installed = []
    for name in NAMES:
        entry = report['atlases'][name]
        source = ART/'prepared'/f'{name}-8dir-v1.png'
        assert hashlib.sha256(source.read_bytes()).hexdigest() == entry['runtime_sha256']
        shutil.copyfile(source,out/source.name)
        frames = entry['frames']
        values = []
        for d in range(8):
            group = frames[d:d+1] if name.endswith('idle') else frames[d*4:d*4+4]
            scale = group[0]['draw_scale_compensation']
            assert all(abs(f['draw_scale_compensation']-scale)<1e-9 for f in group)
            values.append(f'{scale:.9f}f')
        rows.append('    {'+', '.join(values)+'}, /* '+name+' */')
        installed.append({'name':name,'path':'assets/monsters/'+source.name,
                          'sha256':entry['runtime_sha256']})
    header = ('/* Generated by scripts/install_monster_assets.py; do not hand edit. */\n'
              '#ifndef PALDO_MONSTER_ATLAS_DATA_H\n#define PALDO_MONSTER_ATLAS_DATA_H\n'
              'static const float monster_draw_scale[MONSTER_ATLAS_COUNT][HERO_DIRECTIONS] = {\n'
              +'\n'.join(rows)+'\n};\n#endif\n')
    (ROOT/'src/monster_atlas_data.h').write_text(header,encoding='utf-8')
    (ART/'runtime.json').write_text(json.dumps({'installed':installed,
        'direction_order':report['direction_order'],'cell':192,'foot_root':[96,176],
        'unused_candidate':'butcher-attack: no separate basic-attack AI pattern'},indent=2)+'\n',encoding='utf-8')
    print('Installed six approved atlases; generated per-direction scale contract; masters unchanged.')


if __name__ == '__main__':
    main()
